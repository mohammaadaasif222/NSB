/**
 * The footer's line icons, traced from the Figma node.
 *
 * Each keeps the viewBox the design exports it at rather than being normalised
 * to a 24px square: the four contact glyphs are drawn at four different sizes
 * and squaring them would change the weight of the hairline each is stroked
 * with. The stroke is `currentColor`, so a row supplies its own ink — the
 * design draws all of these in `Gray 6 White`, but the hover states need to be
 * able to move them.
 *
 * Kept here rather than in the shared `icons.tsx`, whose icons are all 24px
 * squares on a common `<Svg>` wrapper. These do not fit that contract.
 */

